/** One ledger line. An item with no evidence is OPEN; an owner gate is a DECISION for Chris, never "proven". */
export function renderItem({ text, checked = false, evidence = "", ownerGate = false }) {
  const clean = text.replace(/\s+/g, " ").trim();
  const short = clean.length > 190 ? `${clean.slice(0, 187)}...` : clean;
  if (ownerGate) return `- DECISION (Chris): ${short}`;
  if (checked && evidence.trim()) return `- PROVEN: ${short}`;
  return checked ? `- OPEN (ticked, but no evidence file or PR named): ${short}` : `- OPEN: ${short}`;
}

export function parseChecklist(md) {
  const items = [];
  let section = "";
  for (const line of md.split("\n")) {
    const h = /^#{2,3}\s+(.*)$/.exec(line);
    if (h) { section = h[1].trim(); continue; }
    const bullet = /^- \[( |x)\]\s+(.*)$/i.exec(line);
    const row = /^\|\s*\[( |x)\]\s*\|\s*(.*)$/i.exec(line);
    const m = bullet ?? row;
    if (!m) continue;
    const checked = m[1].toLowerCase() === "x";
    const text = m[2].replace(/\|/g, " ").replace(/\*\*/g, "");
    items.push({ section, text, checked, evidence: checked && EVIDENCE.test(text) ? text : "" });
  }
  return items;
}

function group(items) {
  const bySection = new Map();
  for (const item of items) bySection.set(item.section, [...(bySection.get(item.section) ?? []), item]);
  return bySection;
}

export function buildLedger(read = (p) => readFileSync(p, "utf8"), exists = existsSync) {
  const plan = parseChecklist(read("docs/PLAN.md"));
  const golive = parseChecklist(read("docs/GO-LIVE-CHECKLIST.md"));
  const findings = JSON.parse(read("docs/reviews/dispositions/reconciliation-2026-10-01.json"));
  const gates = /### Human \/ owner gates that stay explicit[^\n]*\n\n([\s\S]*?)\n\n/.exec(read("docs/PLAN.md"))?.[1].replace(/\s+/g, " ").trim() ?? "";
  const planProven = plan.filter((i) => i.checked && i.evidence).length;
  const planOpen = plan.filter((i) => !(i.checked && i.evidence));
  const openFindings = findings.filter((f) => f.status === "open");
  const scenarioRows = SCENARIOS.map(([n, name, file]) => ({ n, name, file, ok: exists(file) }));
  const out = [];
  out.push("# Launch ledger", "", "Generated by `node scripts/launch-ledger.mjs` from the committed plan, checklist, scenarios and review records. Do not edit by hand; change the source and run `npm run ledger` (it is regenerated whenever PLAN.md, GO-LIVE-CHECKLIST.md, the scenarios or the review dispositions change).", "");
  out.push("A line is **PROVEN** only when it is ticked and names its evidence. Anything without evidence is **OPEN**. Anything that needs Chris is a **DECISION**. A passing test never stands in for real-provider, legal or accessibility acceptance.", "");
  out.push("## Summary", "");
  out.push(`- Integrated scenarios proven by a committed test file: ${scenarioRows.filter((s) => s.ok).length} of ${scenarioRows.length}`);
  out.push(`- Plan acceptance items proven with named evidence: ${planProven} of ${plan.length}; OPEN: ${planOpen.length}`);
  out.push(`- Old review findings: ${findings.length - openFindings.length} resolved, ${openFindings.length} OPEN`);
  out.push(`- Go-live switches and checks still waiting on Chris: ${golive.filter((i) => !i.checked).length}`, "");
  out.push("## Integrated scenarios (F2-A, F2-B)", "", "| # | Scenario | Evidence file | State |", "|---|---|---|---|");
  for (const s of scenarioRows) out.push(`| ${s.n} | ${s.name} | \`${s.file}\` | ${s.ok ? "PROVEN (runs in CI)" : "OPEN (file missing)"} |`);
  out.push("", "Connection check: `tests/connection-check.test.ts` (every To do button and Related link points at a real page).", "");
  out.push("## Old review findings still open", "");
  if (!openFindings.length) out.push("- None.");
  for (const f of openFindings) out.push(renderItem({ text: `${f.findingId}: ${f.evidence}` }));
  out.push("", "## Plan acceptance items still open", "");
  for (const [section, items] of group(planOpen)) {
    out.push(`### ${section || "(no heading)"}`, "");
    for (const i of items) out.push(renderItem(i));
    out.push("");
  }
  out.push("## Go-live switches and checks waiting on Chris", "", "Each line is a real-world step (accounts, keys, wording, approvals). Nothing here is switched on by this ledger.", "");
  for (const [section, items] of group(golive.filter((i) => !i.checked))) {
    out.push(`### ${section || "(no heading)"}`, "");
    for (const i of items) out.push(renderItem({ ...i, ownerGate: true }));
    out.push("");
  }
  out.push("## Human / owner gates that stay explicit", "", gates || "(see docs/PLAN.md)", "");
  out.push("## Owner authorization", "", "Only Chris fills this in, in writing, when he decides to launch:", "", "Owner authorization: ____", "");
  return out.join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = buildLedger();
  if (process.argv.includes("--check")) {
    const current = existsSync("docs/LAUNCH-LEDGER.md") ? readFileSync("docs/LAUNCH-LEDGER.md", "utf8") : "";
    if (current !== text) { console.error("docs/LAUNCH-LEDGER.md is stale: run npm run ledger and commit it."); process.exit(1); }
    console.log("Launch ledger is current.");
  } else {
    writeFileSync("docs/LAUNCH-LEDGER.md", text);
    console.log(`Wrote docs/LAUNCH-LEDGER.md (${text.split("\n").length} lines).`);
  }
}
