// F2-D (WU-F8): generates docs/LAUNCH-LEDGER.md — what is proven, what is still open, and what only Chris can decide.
// Reads only committed files, writes no dates, so the output is the same every run until a source file changes.
// Usage: node scripts/launch-ledger.mjs          (rewrite docs/LAUNCH-LEDGER.md)
//        node scripts/launch-ledger.mjs --check  (fail if the committed ledger is stale)
